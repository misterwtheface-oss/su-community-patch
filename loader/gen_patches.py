"""patches.json -> patches_gen.h (compiled into the loader) + suucp.ini (default switches).

Checks every edit's `expect` bytes against the baseline exe first, so a typo in the table fails the build instead of
the game. Usage: python gen_patches.py [path\\to\\SiralimUltimate.exe]
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_EXE = os.path.join(HERE, "..", "..", "_baseline", "su_2x_steambuild_20548371", "game", "SiralimUltimate.exe")


def load_exe(path):
    import pefile
    pe = pefile.PE(path, fast_load=True)
    return pe, pe.OPTIONAL_HEADER.ImageBase


def main():
    spec = json.load(open(os.path.join(HERE, "patches.json"), encoding="utf-8"))
    b = spec["build"]
    base = int(b["image_base"], 16)
    exe = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_EXE
    pe = None
    if os.path.exists(exe):
        pe, _ = load_exe(exe)
        assert pe.FILE_HEADER.TimeDateStamp == int(b["timestamp"], 16), "exe timestamp differs from patches.json build"
        assert pe.OPTIONAL_HEADER.SizeOfImage == int(b["size_of_image"], 16), "exe SizeOfImage differs"
    else:
        print("warning: baseline exe not found, expect-bytes not checked:", exe)

    ids = [p["id"] for p in spec["patches"]]
    assert len(ids) == len(set(ids)), "duplicate patch id"
    out = ["/* generated by gen_patches.py from patches.json; do not edit */", "#pragma once", ""]
    version = open(os.path.join(HERE, "VERSION")).read().strip()
    out.append('#define SUUCP_VERSION "%s"' % version)
    out.append("#define SUUCP_TIMESTAMP 0x%08Xu" % int(b["timestamp"], 16))
    out.append("#define SUUCP_SIZE_OF_IMAGE 0x%08Xu" % int(b["size_of_image"], 16))
    out.append("")
    edits_c, patches_c = [], []
    # The tail of .text past VirtualSize is mapped and zero-filled in memory (but not in the file): free space for our
    # constants and hook code. Expected bytes there are zeros, checked again by the loader at runtime.
    cave = (int(b["cave_start"], 16), int(b["cave_end"], 16)) if "cave_start" in b else None
    # Extra code caves: the slack of read-only sections past VirtualSize (mapped, zero-filled, never referenced). The
    # loader writes them like any edit and then makes those pages execute-read.
    xcaves = [(int(x["start"], 16), int(x["end"], 16)) for x in b.get("xcaves", [])]
    written = {}                                         # address -> patch id that owns it
    for p in spec["patches"]:
        first = len(edits_c)
        for e in p["edits"]:
            va = int(e["va"], 16)
            ex, wr = bytes.fromhex(e["expect"]), bytes.fromhex(e["write"])
            assert len(ex) == len(wr) and 0 < len(ex) <= 32, "%s: expect/write length" % p["id"]
            in_cave = (cave and cave[0] <= va and va + len(ex) <= cave[1]) or                 any(lo <= va and va + len(ex) <= hi for lo, hi in xcaves)
            for a in range(va, va + len(ex)):
                assert a not in written, "%s @%#x overlaps an edit of %s" % (p["id"], a, written.get(a))
                written[a] = p["id"]
            if in_cave:
                assert ex == bytes(len(ex)), "%s: cave bytes must be expected as zeros" % p["id"]
            elif pe is not None:
                got = pe.get_data(va - base, len(ex))
                assert got == ex, "%s @%#x: exe has %s, patches.json expects %s" % (p["id"], va, got.hex(), ex.hex())
            arr = lambda bs: "{" + ",".join("0x%02X" % x for x in bs) + "}"
            edits_c.append("    {0x%08Xu, %d, %s, %s}," % (va - base, len(ex), arr(ex), arr(wr)))
        for rv in p.get("reserves", []):                 # runtime state (flags, saved values) declared by the patch
            for a in range(int(rv["start"], 16), int(rv["end"], 16)):
                assert written.get(a, p["id"]) == p["id"], "%s reserve @%#x overlaps %s" % (p["id"], a, written[a])
                written[a] = p["id"]
        patches_c.append('    {"%s", %d, %d, %d, "%s"},  /* %s */' % (p["id"], p["default"], first, len(p["edits"]),
                                                                    p.get("group", ""), p["title"].replace("*/", "")))
    out += ["static const SuucpEdit g_edits[] = {"] + edits_c + ["};", ""]
    out += ["static const unsigned g_xcaves[][2] = {"] + (["    {0x%08Xu, 0x%Xu}," % (lo - base, hi - lo) for lo, hi in xcaves]
                                                       or ["    {0, 0},"]) + ["};", ""]
    out += ["static const SuucpPatch g_patches[] = {"] + patches_c + ["};", ""]
    hooks = ['    {"%s", 0x%08Xu, (void *)%s},' % (p["id"], int(h["slot_va"], 16) - base, h["symbol"])
             for p in spec["patches"] for h in p.get("runtime_hooks", [])]
    out += ["static const SuucpHook g_hooks[] = {"] + (hooks or ['    {"", 0, 0},']) + ["};", ""]
    open(os.path.join(HERE, "patches_gen.h"), "w", encoding="utf-8", newline="\n").write("\n".join(out))

    # text corrections from the bug registry (bugs/*.json "text_fix"); compiled into the DLL, applied via
    # localization_override at startup from the player's own CSVs (see text.c)
    import glob
    def cstr(t):
        out = []
        for byte in t.encode("utf-8"):
            ch = chr(byte)
            out.append(ch if 32 <= byte < 127 and ch not in '"\\?' else "\\%03o" % byte)   # octal escapes (max 3 digits) cannot swallow a following character
        return '"' + "".join(out) + '"'
    texts = []
    for f in sorted(glob.glob(os.path.join(HERE, "..", "bugs", "SU-*.json"))):
        r = json.load(open(f, encoding="utf-8"))
        for t in r.get("text_fix", []):
            texts.append((t["file"], t["key"], t["en_proposed"], t.get("en_current_sha256", ""), 1 if t.get("new_row") else 0,
                          r["id"], t.get("copy_other_languages_from", ""), t.get("en_find", "")))
    texts.sort(key=lambda x: (x[0], x[1]))
    tl = ["/* generated by gen_patches.py from bugs/*.json text_fix; do not edit */", "#pragma once",
          "static const SuucpText g_text[] = {"]
    tl += ["    {%s, %s, %s, %s, %d, %s, %s, %s}," % (cstr(a), cstr(b), cstr(c), cstr(d), e, cstr(g), cstr(h), cstr(i))
           for a, b, c, d, e, g, h, i in texts]
    if not texts:
        tl.append("    {0, 0, 0, 0, 0, 0, 0, 0},")
    tl.append("};")
    open(os.path.join(HERE, "text_gen.h"), "w", encoding="utf-8", newline="\n").write("\n".join(tl) + "\n")

    ini = ["; Siralim Ultimate Unofficial Community Patch - fix switches (1 = on, 0 = off)", "[fixes]"]
    for p in spec["patches"]:
        ini.append("; %s" % p["title"])
        ini.append("%s=%d" % (p["id"], p["default"]))
    groups = sorted({p["group"] for p in spec["patches"] if p.get("group")} | {"heavy"})
    ini += ["", "; Groups switch whole sets of fixes on or off (a fix runs only if its own switch AND its group are on).",
            "; heavy = large rebuilds of core battle code (most crash-prone); set heavy=0 to test without them.", "[groups]"]
    ini += ["%s=1" % g for g in groups]
    ini += ["", "; In-game text corrections (written to localization_override at startup). all=0 turns them all off;",
            "; a bug id (e.g. SU-0077=0) turns off that one correction.", "[text]", "all=1"]
    open(os.path.join(HERE, "suucp.ini"), "w", encoding="utf-8", newline="\r\n").write("\n".join(ini) + "\n")
    print("ok: %d patches, %d edits, %d text corrections%s" % (len(patches_c), len(edits_c), len(texts), "" if pe else " (unchecked)"))


if __name__ == "__main__":
    main()
